"""Build source-bound vector PDFs with four graphical frontmatter pages."""

from __future__ import annotations

import hashlib
import os
import tempfile
from pathlib import Path
from typing import TYPE_CHECKING, Final

import pymupdf
from pydantic import TypeAdapter

from crosstalk.dossier_figures import figure_plates
from crosstalk.dossier_layout import TEAL, Label, PageCanvas, TextStyle, wrap_text
from crosstalk.dossier_methods import draw_methods, draw_review
from crosstalk.dossier_pages import draw_cover, draw_coverage
from crosstalk.dossier_records import DossierBuild
from crosstalk.models import AcquisitionError, file_digest, safe_directory
from crosstalk.pdf_adapter import preview_png, text_blocks
from crosstalk.records import write_records

if TYPE_CHECKING:
    from crosstalk.dossier_records import DossierInput

PDF_BYTES: Final = TypeAdapter(bytes)
NONE_VALUE: Final = TypeAdapter(type(None))


def _check_sources(root: Path, content: DossierInput) -> None:
    """Refuse changed inputs, parent symlinks or source paths outside the project."""
    if root.is_symlink() or not root.is_dir():
        raise AcquisitionError("Dossier root must be a physical project directory")
    for binding in content.source_bindings:
        relative = Path(binding.path)
        if (
            relative.is_absolute()
            or not relative.parts
            or any(part in {".", ".."} for part in relative.parts)
        ):
            raise AcquisitionError("Dossier source binding must be project-local")
        path = root
        for part in relative.parts:
            path /= part
            if path.is_symlink():
                raise AcquisitionError("Dossier source binding contains a symlink")
        if file_digest(path) != binding.sha256:
            raise AcquisitionError(f"Dossier source changed: {binding.path}")


def _atomic_bytes(path: Path, payload: bytes) -> None:
    """Publish local generated bytes without following a terminal symlink."""
    if path.is_symlink():
        raise AcquisitionError("Dossier output path is a symlink")
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o600
    descriptor, temporary = tempfile.mkstemp(prefix=".dossier-", dir=path.parent)
    with os.fdopen(descriptor, "wb") as stream:
        _ = stream.write(payload)
        stream.flush()
        os.fsync(stream.fileno())
        os.fchmod(stream.fileno(), mode)
    _ = Path(temporary).replace(path)


def _new_canvas(document: pymupdf.Document, number: int) -> PageCanvas:
    """Create one A4 page with consistent page furniture."""
    return PageCanvas(document.new_page(width=595, height=842), number)


def _body_pages(
    document: pymupdf.Document, content: DossierInput, start_page: int = 5
) -> tuple[PageCanvas, ...]:
    """Paginate complete prose and human-readable references without dropping lines."""
    canvases: list[PageCanvas] = []
    canvas = _new_canvas(document, start_page)
    canvases.append(canvas)
    canvas.heading(
        "Methods, evidence and next steps",
        "The graphical summaries are followed by the protocol, "
        + "local observations and source locators.",
        eyebrow="RESEARCH PROTOCOL",
    )
    top = 180.0
    sections = [(section.title, section.paragraphs) for section in content.sections]
    sections.append(
        (
            "Source and build provenance",
            (
                f"Source revision: {content.source_revision}. "
                + f"Observation: {content.observed_at}. "
                + f"Bound input files: {len(content.source_bindings)}. "
                + "Full-archive completeness is not established.",
                f"Example accepted source: {content.evidence.pilot_title}. "
                + f"Source PDF SHA-256: {content.evidence.pilot_sha256 or 'unavailable'}.",
            ),
        )
    )
    sections.append(
        (
            "References and source locators",
            tuple(
                f"[{index}] {reference.label}. {reference.url}"
                for index, reference in enumerate(content.references, start=1)
            ),
        )
    )
    for title, paragraphs in sections:
        if top > 700:
            canvas = _new_canvas(document, len(canvases) + start_page)
            canvases.append(canvas)
            canvas.text(
                Label(
                    (42, 55, 553, 81), "RESEARCH PROTOCOL / CONTINUED", TextStyle(9, "hebo", TEAL)
                )
            )
            top = 101
        canvas.text(Label((42, top, 553, top + 55), title, TextStyle(17, "hebo", TEAL)))
        top += 58
        for paragraph in paragraphs:
            lines = list(wrap_text(paragraph, 497))
            while lines:
                capacity = int((770 - top - 8) / 13.77)
                if capacity < 1:
                    canvas = _new_canvas(document, len(canvases) + start_page)
                    canvases.append(canvas)
                    canvas.text(
                        Label(
                            (42, 55, 553, 81), title + " / continued", TextStyle(10, "hebo", TEAL)
                        )
                    )
                    top = 101
                    capacity = int((770 - top - 8) / 13.77)
                selected, lines = lines[:capacity], lines[capacity:]
                height = len(selected) * 13.77 + 8
                canvas.text(Label((42, top, 553, top + height), "\n".join(selected)))
                top += height + 10
        top += 14
    return tuple(canvases)


def build_dossier(root: Path, content: DossierInput) -> DossierBuild:
    """Render all pages in memory, recheck source hashes, then publish artifacts."""
    root = root.absolute()
    _check_sources(root, content)
    pdf_directory = safe_directory(root, "output/pdf")
    figure_directory = safe_directory(root, "output/figures")
    report_directory = safe_directory(root, "output/reports")
    pdf_path = pdf_directory / "CrossTalk-research-dossier.pdf"
    preview_paths = tuple(
        figure_directory / f"frontmatter-page-{index:02d}.png" for index in range(1, 5)
    )
    input_path = report_directory / "dossier-input.jsonl"
    receipt_path = report_directory / "dossier-build.jsonl"
    if any(path.is_symlink() for path in (pdf_path, *preview_paths, input_path, receipt_path)):
        raise AcquisitionError("Dossier output path is a symlink")
    encoded = content.model_dump_json().encode()
    with pymupdf.open() as document:
        canvases: list[PageCanvas] = []
        for index, draw in enumerate(
            (draw_cover, draw_coverage, draw_methods, draw_review), start=1
        ):
            canvas = _new_canvas(document, index)
            draw(canvas, content)
            canvases.append(canvas)
        plates = figure_plates(document, root, content)
        body = _body_pages(document, content, len(canvases) + len(plates) + 1)
        _ = NONE_VALUE.validate_python(
            getattr(document, "set_metadata")(  # noqa: B009 -- dependency typing boundary.
                {
                    "title": content.title,
                    "author": "; ".join(author.name for author in content.authors),
                    "subject": content.subtitle,
                    "keywords": "CrossTalk; literature review; corpus linguistics; "
                    + "visual analysis; research protocol",
                }
            )
        )
        for page in document:
            blocks = text_blocks(page)
            if not blocks or any(
                block[0] < 0 or block[1] < 0 or block[2] > 595.1 or block[3] > 842.1
                for block in blocks
            ):
                raise AcquisitionError("Dossier page text is empty or exceeds page geometry")
        payload = PDF_BYTES.validate_python(
            getattr(document, "tobytes")(  # noqa: B009 -- dependency typing boundary.
                garbage=4, deflate=True, no_new_id=True
            )
        )
        previews = tuple(preview_png(document[index], 1.5) for index in range(4))
        pages = len(canvases) + len(plates) + len(body)
        text_boxes = sum(canvas.text_boxes for canvas in (*canvases, *plates, *body))
    _check_sources(root, content)
    result = DossierBuild(
        pdf_path=pdf_path.relative_to(root).as_posix(),
        pages=pages,
        preview_paths=tuple(path.relative_to(root).as_posix() for path in preview_paths),
        input_sha256=hashlib.sha256(encoded).hexdigest(),
        pdf_sha256=hashlib.sha256(payload).hexdigest(),
        text_boxes=text_boxes,
    )
    for path, preview in zip(preview_paths, previews, strict=True):
        _atomic_bytes(path, preview)
    _atomic_bytes(pdf_path, payload)
    write_records(input_path, (content,))
    write_records(receipt_path, (result,))
    return result
